#!/usr/bin/env node
/* Generates db/seed.sql from the data the prototype already carries:
   the policy library, the tracker form mapping, and the user directory.
   Re-runnable — every insert is idempotent.

   Usage: node scripts/build-seed-sql.js */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const sandbox = {document: {addEventListener() {}, getElementById: () => null}, window: {}, console};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(root, 'data/policy-form-map.js'), 'utf8'), sandbox);
vm.runInContext(fs.readFileSync(path.join(root, 'app.js'), 'utf8'), sandbox);
// the mapping index is built at page load, so build it here too
vm.runInContext('buildFormMapIndex();', sandbox);

// top-level `const` in a vm script lives in the context's lexical scope, not on
// the sandbox object, so pull the values out with an expression
const {POLICIES, SECTIONS, FORM_ROLES, FORM_DEPTS, FORM_FACILITIES, EMPLOYEES, POLICY_TO_FORMS} =
  vm.runInContext('({POLICIES, SECTIONS, FORM_ROLES, FORM_DEPTS, FORM_FACILITIES, EMPLOYEES, POLICY_TO_FORMS})', sandbox);

const q = v => v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const out = [];
const w = (...lines) => out.push(...lines);

// Facilities carry a state code because the regulatory crosswalk depends on it.
// CONFIRM these three before go-live — the rest are Louisiana.
const STATE = {'Freedom Plainview': 'TX', 'Freedom Greenville': 'MS', 'Freedom Magnolia': 'MS'};
const code = name => name.replace('Freedom ', '').replace(/[^A-Za-z]/g, '').slice(0, 6).toUpperCase();

w('-- GENERATED by scripts/build-seed-sql.js — do not edit by hand.',
  '-- Safe to re-run: every statement is idempotent.',
  'begin;', '');

w('-- ---------------------------------------------------------- reference');
SECTIONS.forEach((s, i) => w(`insert into toc_section (name, sort_order) values (${q(s)}, ${i + 1}) on conflict (name) do nothing;`));
w('');
FORM_FACILITIES.filter(f => f !== 'Enterprise / Corporate').forEach(f =>
  w(`insert into facility (code, name, state_code) values (${q(code(f))}, ${q(f)}, ${q(STATE[f] || 'LA')}) on conflict (code) do nothing;`));
w('');
FORM_DEPTS.forEach(d => w(`insert into department (name) values (${q(d)}) on conflict (name) do nothing;`));
w('');
FORM_ROLES.forEach(r => w(`insert into hospital_role (name) values (${q(r)}) on conflict (name) do nothing;`));
w('');

w('-- ----------------------------------------------------------- policies');
POLICIES.forEach(p => w(
  `insert into policy (section_id, policy_number, title, risk_level, risk_basis, regulatory_driver, status)` +
  ` select id, ${q(p.policy)}, ${q(p.title)}, ${p.risk}, ${q(p.basis)}, ${q(p.regulatory)}, 'active'` +
  ` from toc_section where name = ${q(p.section)} on conflict (section_id, policy_number, title) do nothing;`));
w('');

w('-- ------------------------------------- forms expected by the tracker');
let links = 0;
POLICIES.forEach(p => {
  const forms = POLICY_TO_FORMS.get(String(p.policy)) || [];
  forms.forEach(f => {
    links++;
    w(`insert into policy_expected_form (policy_id, form_number) select p.id, ${q(f)} from policy p` +
      ` join toc_section s on s.id = p.section_id where p.policy_number = ${q(p.policy)} and p.title = ${q(p.title)}` +
      ` and s.name = ${q(p.section)} on conflict do nothing;`);
  });
});
w('');

w('-- --------------------------------------------------------- directory');
EMPLOYEES.forEach(e => {
  w(`insert into app_user (employee_no, first_name, last_name, email, upn, primary_facility_id, security_role, is_shared_mailbox, status)` +
    ` values (${q(e.id)}, ${q(e.first)}, ${q(e.last)}, ${q(e.email)}, ${q(e.email)},` +
    ` ${e.facility === 'Enterprise / Corporate' ? 'null' : `(select id from facility where name = ${q(e.facility)})`},` +
    ` ${q(e.securityRole || 'Employee')}, ${e.shared ? 'true' : 'false'}, ${q(e.status.toLowerCase())})` +
    ` on conflict (email) do update set first_name = excluded.first_name, last_name = excluded.last_name,` +
    ` security_role = excluded.security_role, status = excluded.status;`);
  (e.roles || []).forEach(r => w(
    `insert into user_role (user_id, role_id) select u.id, r.id from app_user u, hospital_role r` +
    ` where u.email = ${q(e.email)} and r.name = ${q(r)} on conflict do nothing;`));
  (e.departments || []).forEach(d => w(
    `insert into user_department (user_id, department_id) select u.id, d.id from app_user u, department d` +
    ` where u.email = ${q(e.email)} and d.name = ${q(d)} on conflict do nothing;`));
});

w('', 'commit;');
fs.writeFileSync(path.join(root, 'db/seed.sql'), out.join('\n') + '\n');
console.log(`db/seed.sql — ${SECTIONS.length} sections, ${FORM_FACILITIES.length - 1} facilities, ` +
  `${FORM_DEPTS.length} departments, ${FORM_ROLES.length} roles, ${POLICIES.length} policies, ` +
  `${links} expected form links, ${EMPLOYEES.length} users`);
